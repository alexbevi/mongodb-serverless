#!/usr/bin/env node
// Emits explicit named re-exports of the mongodb surface.
//
// `export * from 'mongodb'` does not work: mongodb is CJS with no exports
// field, so a star export forwards nothing to an ESM consumer. Each name has
// to be listed.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

const mongodb = require('mongodb');

const { version } = require('mongodb/package.json');

const OVERRIDDEN = new Set(['MongoClient']);

// Some names are exported at runtime but marked "Excluded from this release
// type" in mongodb.d.ts, meaning the driver considers them internal.
// Re-exporting those would not typecheck, so skip them.
const types = readFileSync(require.resolve('mongodb/mongodb.d.ts'), 'utf8');

const excluded = new Set(
  [...types.matchAll(/\/\* Excluded from this release type: (\w+) \*\//g)].map(m => m[1])
);

const names = Object.keys(mongodb)
  .filter(name => !OVERRIDDEN.has(name) && !excluded.has(name))
  .sort();

const skipped = Object.keys(mongodb).filter(name => excluded.has(name));

const output = `// Generated by scripts/generate-reexports.mjs. Do not edit.
//
// mongodb is CJS with no exports field, so \`export *\` forwards nothing to an
// ESM consumer. Every name is listed explicitly. MongoClient is omitted; the
// driver exports its own.
//
// Generated against mongodb@${version}.
${skipped.length > 0 ? `//\n// Excluded as internal to the driver: ${skipped.sort().join(', ')}.\n` : ''}
export {
${names.map(name => `  ${name}`).join(',\n')}
} from 'mongodb';

export type * from 'mongodb';

/** Names mongodb exports at runtime but excludes from its public types. */
export const INTERNAL_MONGODB_EXPORTS: readonly string[] = [
${skipped
  .sort()
  .map(name => `  '${name}'`)
  .join(',\n')}
];
`;

const target = new URL('../src/generated/reexports.ts', import.meta.url);

writeFileSync(target, output);

console.log(
  `Wrote ${names.length} re-exports for mongodb@${version}` +
    (skipped.length > 0 ? ` (${skipped.length} internal names skipped)` : '')
);
